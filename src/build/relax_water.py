import argparse
import math
from pathlib import Path

from ..logger import generate_logger

LOGGER = generate_logger(__name__)

DEFAULT_WATER_RESNAMES = ("WAT", "HOH", "SOL")
KCAL_PER_ANGSTROM2_TO_KJ_PER_NANOMETER2 = 418.4


def add_subcmd(subparsers):
    parser = subparsers.add_parser(
        "relax_water",
        help="Relax tiled solvent coordinates with short restrained MD",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )

    parser.add_argument(
        "-p",
        "--parm",
        required=True,
        type=str,
        help="Amber parameter file (.parm7, .prmtop)",
    )
    parser.add_argument(
        "-x",
        "--rst",
        required=True,
        type=str,
        help="Amber coordinate file (.rst7, .inpcrd)",
    )
    parser.add_argument(
        "-o",
        "--output",
        default="relaxed.rst7",
        type=str,
        help="Output Amber restart file",
    )
    parser.add_argument(
        "--pdb-output",
        default="relaxed.pdb",
        type=str,
        help="Output PDB file",
    )
    parser.add_argument(
        "--steps",
        default=2000,
        type=int,
        help="Number of 2 fs NVT relaxation steps",
    )
    parser.add_argument(
        "--minimize-iterations",
        default=100,
        type=int,
        help="Maximum energy-minimization iterations",
    )
    parser.add_argument(
        "--temperature",
        default=300.0,
        type=float,
        help="Relaxation temperature [K]",
    )
    parser.add_argument(
        "--restraint",
        default=10.0,
        type=float,
        help="Non-water positional restraint [kcal/mol/angstrom^2]",
    )
    parser.add_argument(
        "--water-resname",
        nargs="+",
        default=list(DEFAULT_WATER_RESNAMES),
        help="Water residue names excluded from positional restraints",
    )
    parser.add_argument(
        "--seed",
        default=2026,
        type=int,
        help="Random seed",
    )

    parser.set_defaults(func=run)


def _validate_args(args):
    for path in (args.parm, args.rst):
        if not Path(path).is_file():
            raise FileNotFoundError(path)
    if args.steps <= 0:
        raise ValueError("--steps must be positive")
    if args.minimize_iterations < 0:
        raise ValueError("--minimize-iterations must be non-negative")
    if args.temperature <= 0:
        raise ValueError("--temperature must be positive")
    if args.restraint < 0:
        raise ValueError("--restraint must be non-negative")


def _box_lengths_and_angles(box_vectors):
    import numpy as np

    vectors = np.asarray(box_vectors, dtype=float)
    lengths = np.linalg.norm(vectors, axis=1)

    def angle(vector1, vector2):
        cosine = np.dot(vector1, vector2) / (
            np.linalg.norm(vector1) * np.linalg.norm(vector2)
        )
        return math.degrees(math.acos(float(np.clip(cosine, -1.0, 1.0))))

    alpha = angle(vectors[1], vectors[2])
    beta = angle(vectors[0], vectors[2])
    gamma = angle(vectors[0], vectors[1])
    return [*lengths, alpha, beta, gamma]


def _add_solute_restraints(system, topology, positions, water_resnames, strength):
    from openmm import CustomExternalForce, unit

    if strength == 0:
        return 0

    water_names = {name.upper() for name in water_resnames}
    force = CustomExternalForce("0.5*k*periodicdistance(x, y, z, x0, y0, z0)^2")
    force.addGlobalParameter(
        "k",
        strength * KCAL_PER_ANGSTROM2_TO_KJ_PER_NANOMETER2,
    )
    for parameter in ("x0", "y0", "z0"):
        force.addPerParticleParameter(parameter)

    restrained_atoms = 0
    for atom in topology.atoms():
        if atom.residue.name.upper() in water_names:
            continue
        reference = positions[atom.index].value_in_unit(unit.nanometer)
        force.addParticle(atom.index, reference)
        restrained_atoms += 1

    if restrained_atoms:
        system.addForce(force)
    return restrained_atoms


def _write_restart(path, state, atom_count, simulation_time):
    import numpy as np
    from openmm import unit
    from parmed.amber import Rst7

    positions = state.getPositions(asNumpy=True).value_in_unit(unit.angstrom)
    velocities = state.getVelocities(asNumpy=True).value_in_unit(
        unit.angstrom / unit.picosecond
    )
    box_vectors = state.getPeriodicBoxVectors(asNumpy=True).value_in_unit(unit.angstrom)

    restart = Rst7(
        natom=atom_count,
        title="Water-relaxed restart generated by mdtbx",
    )
    restart.time = simulation_time
    restart.coordinates = np.asarray(positions)
    restart.vels = np.asarray(velocities)
    restart.box = _box_lengths_and_angles(box_vectors)
    restart.write(str(path))


def _relax(args):
    from openmm import LangevinMiddleIntegrator, unit
    from openmm.app import (
        AmberInpcrdFile,
        AmberPrmtopFile,
        HBonds,
        PDBFile,
        PME,
        Simulation,
    )

    parameters = AmberPrmtopFile(args.parm)
    coordinates = AmberInpcrdFile(args.rst)
    if coordinates.boxVectors is None:
        raise ValueError("Periodic box vectors are required")

    parameters.topology.setPeriodicBoxVectors(coordinates.boxVectors)
    system = parameters.createSystem(
        nonbondedMethod=PME,
        nonbondedCutoff=1.0 * unit.nanometer,
        constraints=HBonds,
        rigidWater=True,
    )
    restrained_atoms = _add_solute_restraints(
        system,
        parameters.topology,
        coordinates.positions,
        args.water_resname,
        args.restraint,
    )

    integrator = LangevinMiddleIntegrator(
        args.temperature * unit.kelvin,
        1.0 / unit.picosecond,
        0.002 * unit.picoseconds,
    )
    integrator.setRandomNumberSeed(args.seed)
    simulation = Simulation(parameters.topology, system, integrator)
    simulation.context.setPositions(coordinates.positions)

    platform_name = simulation.context.getPlatform().getName()
    LOGGER.info(f"OpenMM platform: {platform_name}")
    LOGGER.info(f"Restrained non-water atoms: {restrained_atoms}")

    simulation.minimizeEnergy(maxIterations=args.minimize_iterations)
    simulation.context.setVelocitiesToTemperature(
        args.temperature * unit.kelvin,
        args.seed,
    )
    simulation.step(args.steps)

    state = simulation.context.getState(
        getPositions=True,
        getVelocities=True,
        enforcePeriodicBox=True,
    )
    box_vectors = state.getPeriodicBoxVectors()
    parameters.topology.setPeriodicBoxVectors(box_vectors)

    output_path = Path(args.output)
    pdb_path = Path(args.pdb_output)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    pdb_path.parent.mkdir(parents=True, exist_ok=True)

    simulation_time = args.steps * 0.002
    _write_restart(
        output_path,
        state,
        parameters.topology.getNumAtoms(),
        simulation_time,
    )
    with pdb_path.open("w") as handle:
        PDBFile.writeFile(
            parameters.topology,
            state.getPositions(),
            handle,
            keepIds=True,
        )


def run(args):
    _validate_args(args)
    _relax(args)
    LOGGER.info(f"{args.output} generated")
    LOGGER.info(f"{args.pdb_output} generated")
